#!/usr/bin/env python3
"""Year-to-year spread of the JJA jet position, to judge whether the climatological shifts exceed sampling noise.

Jet proxy: zonal-mean surface zonal wind stress var180 (sam_wind/{exp}_taux.nc, 100 yr monthly; LIG 98 yr).
SLP index: zonal-mean psl 40S minus 65S ({exp}/100years/slp_mergetime.nc).
Each year: JJA mean (Jun, Jul, Aug of the same calendar year), latitude of the taux maximum (3-point parabola, 30-70S).
Output: numbers_interannual.txt
"""
import numpy as np
import netCDF4 as nc
from pathlib import Path
from scipy import stats

ROOT = Path('/work/ba1066/a270064/cc_projects/aabw_5exps')
HERE = ROOT / 'explore/westerly_mechanism'
EXPS = ['pi', 'mh', 'lig', 'lgm', 'mis']
LABEL = {'pi': 'PI', 'mh': 'MH', 'lig': 'LIG', 'lgm': 'LGM', 'mis': 'MIS3'}


def yearly_jja(x, time):
    """x(time, lat) monthly; time as YYYYMMDD.f -> array(year, lat) of JJA means for complete JJA years."""
    ymd = np.floor(time).astype(np.int64)
    yr, mo = ymd // 10000, (ymd // 100) % 100
    out, yrs = [], []
    for y in np.unique(yr):
        m = (yr == y) & np.isin(mo, [6, 7, 8])
        if m.sum() == 3:
            out.append(x[m].mean(0))
            yrs.append(y)
    return np.array(out), np.array(yrs)


def peak_fit(lat, y, lo=-70, hi=-30):
    idx = np.where((lat >= lo) & (lat <= hi))[0]
    i = idx[np.argmax(y[idx])]
    c = np.polyfit(lat[i - 1:i + 2], y[i - 1:i + 2], 2)
    pl = -c[1] / (2 * c[0])
    return pl, np.polyval(c, pl)


lines = ['# Interannual JJA spread (generated by interannual_jet.py)',
         '# taux = zonal-mean var180 [Pa]; lat by 3-point parabola; SLP40-65 = zonal-mean psl difference [hPa]',
         '# columns: n years | taux-max lat mean, sd, s.e. | taux max mean, sd | SLP40-65 mean, sd | Welch t-test vs PI for lat (p)']
res = {}
for e in EXPS:
    d = nc.Dataset(ROOT / 'sam_wind' / f'{e}_taux.nc')
    lat = d['lat'][:].data
    o = np.argsort(lat)
    lat = lat[o]
    tx = d['var180'][:].data[:, o, :].mean(-1)
    t = d['time'][:].data
    ty, yrs = yearly_jja(tx, t)
    pk = np.array([peak_fit(lat, row) for row in ty])
    s = nc.Dataset(ROOT / e / '100years' / 'slp_mergetime.nc')
    slat = s['lat'][:].data
    so = np.argsort(slat)
    slat = slat[so]
    ps = s['psl'][:].data[:, so, :].mean(-1) / 100.
    py, _ = yearly_jja(ps, s['time'][:].data)
    idx = np.array([np.interp(-40, slat, r) - np.interp(-65, slat, r) for r in py])
    res[e] = dict(lat=pk[:, 0], val=pk[:, 1], slp=idx, n=len(yrs), y0=yrs[0], y1=yrs[-1])
for e in EXPS:
    r = res[e]
    p = stats.ttest_ind(r['lat'], res['pi']['lat'], equal_var=False).pvalue if e != 'pi' else np.nan
    lines.append(f'{LABEL[e]:5s} n={r["n"]:3d} ({r["y0"]}-{r["y1"]}) | lat {r["lat"].mean():7.2f} sd {r["lat"].std(ddof=1):5.2f} '
                 f'se {r["lat"].std(ddof=1)/np.sqrt(r["n"]):5.2f} | taux {r["val"].mean():.4f} sd {r["val"].std(ddof=1):.4f} | '
                 f'SLP40-65 {r["slp"].mean():6.2f} sd {r["slp"].std(ddof=1):5.2f} | p(lat vs PI) {p:.2e}')
(HERE / 'numbers_interannual.txt').write_text('\n'.join(lines) + '\n')
print('\n'.join(lines))
