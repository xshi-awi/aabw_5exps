def peak(lat, y, lo, hi, mode='max'):
    """Grid-row extreme of y within [lo,hi] (deg, lo<hi, negative = S) and 3-point parabolic vertex."""
    m = (lat >= lo) & (lat <= hi) & np.isfinite(y)
    idx = np.where(m)[0]
    if idx.size == 0:
        return np.nan, np.nan, np.nan, np.nan
    yy = y[idx] if mode == 'max' else -y[idx]
    i = idx[np.nanargmax(yy)]
    glat, gval = lat[i], y[i]
    # parabolic vertex only for an interior extreme (both neighbours inside the window);
    # an extreme on the window edge returns fit = NaN (not a real peak in that window)
    if i == idx[0] or i == idx[-1]:
        return glat, gval, np.nan, np.nan
    c = np.polyfit(lat[i - 1:i + 2], y[i - 1:i + 2], 2)
    plat = -c[1] / (2 * c[0]) if c[0] != 0 else glat
    pval = np.polyval(c, plat)
    return glat, gval, plat, pval


def centroid(lat, y, lo, hi):
    """cos-weighted centroid latitude of a positive profile within [lo,hi]."""
    m = (lat >= lo) & (lat <= hi) & np.isfinite(y)
    w = np.cos(np.deg2rad(lat[m])) * y[m]
    return float(np.sum(lat[m] * w) / np.sum(w))


def zmean(field, valid_frac=0.5):
    """Zonal mean over the last axis ignoring NaN; NaN where fewer than valid_frac of longitudes valid."""
    f = np.asarray(field, dtype=float)
    n = np.sum(np.isfinite(f), axis=-1)
    with np.errstate(invalid='ignore'):
        zm = np.nanmean(f, axis=-1)
    zm[n < valid_frac * f.shape[-1]] = np.nan
    return zm


def ddy(lat, y):
    """Northward derivative in K per 1000 km (lat in deg, ascending)."""
    return np.gradient(y, np.deg2rad(lat)) / A * 1e6


def interp_at(lat, y, x):
    m = np.isfinite(y)
    return float(np.interp(x, lat[m], y[m]))


def mean_band(lat, y, lo, hi):
    """cos(lat)-weighted mean of a zonal-mean profile within [lo,hi]."""
    m = (lat >= lo) & (lat <= hi) & np.isfinite(y)
    w = np.cos(np.deg2rad(lat[m]))
    return float(np.sum(y[m] * w) / np.sum(w))


def lonmask(lon, sector):
    a, b = SECTORS[sector]
    return (lon >= a) & (lon < b) if a < b else (lon >= a) | (lon < b)


def season(da, s):
    return da.isel(time=JJA).mean('time') if s == 'JJA' else da.mean('time')


