#!/bin/bash
# Tracked-change version of revision/response_new.tex between two TexPage commits (2026-11-23).
# Usage: make_diff.sh <TexPage clone> <old commit> <new commit> <out name> <build dir> "<old label>" "<new label>"
# Writes <build dir>/<out name>.tex and .pdf. The build dir gets symlinks to figures/ and letter_figs/
# of the clone, so it compiles exactly as it would inside revision/ on TexPage.
set -euo pipefail
CLONE=$1; OLD=$2; NEW=$3; NAME=$4; B=$5; OLDLAB=$6; NEWLAB=$7
HERE=$(cd "$(dirname "$0")" && pwd)
mkdir -p "$B"
git -C "$CLONE" show "$OLD":revision/response_new.tex > "$B/old_$OLD.tex"
git -C "$CLONE" show "$NEW":revision/response_new.tex > "$B/new_$NEW.tex"
ln -sfn "$CLONE/revision/figures" "$B/figures"
ln -sfn "$CLONE/revision/letter_figs" "$B/letter_figs"
# \hl, \docxcomment, \claudenote and \rfig carry text in their last argument: diff it word by word,
# otherwise a deleted \hl{...} or figure would vanish from the output instead of being struck out.
# latexdiff --preamble needs the Perl module Encode::Locale, missing on Levante, so the default
# preamble block is generated and then replaced by diff_preamble.tex in the python step below.
latexdiff -t CULINECHBAR --graphics-markup=none \
  --append-textcmd="hl,docxcomment,claudenote,rfig" \
  "$B/old_$OLD.tex" "$B/new_$NEW.tex" > "$B/raw_$NAME.tex" 2> "$B/latexdiff_$NAME.err"
python3 - "$B/raw_$NAME.tex" "$B/$NAME.tex" "$OLD" "$NEW" "$OLDLAB" "$NEWLAB" "$HERE/diff_preamble.tex" <<'EOF'
import sys, re
src, dst, old, new, oldlab, newlab, pre = sys.argv[1:]
s = open(src).read()
a, b = "%DIF PREAMBLE EXTENSION ADDED BY LATEXDIFF\n", "%DIF END PREAMBLE EXTENSION ADDED BY LATEXDIFF\n"
assert s.count(a) == 1 and s.count(b) == 1
i, j = s.index(a) + len(a), s.index(b)
s = s[:i] + open(pre).read() + s[j:]
head = ("% Tracked-change version of response_new.tex, made with latexdiff on 2026-11-23. Do not edit;\n"
        f"% it is regenerated by nc_paper/docx_to_tex/pass_20261123/make_diff.sh. Old: TexPage {old}. New: TexPage {new}.\n")
box = (r"\noindent\fbox{\parbox{\dimexpr\linewidth-2\fboxsep\relax}{\small\color{black}"
       f"Tracked changes in this letter. Old version: {oldlab}. New version: {newlab}. "
       r"{\color{blue}\uwave{Blue underlined text}} was added and {\color{red}\sout{red struck-out text}} was deleted. "
       r"Yellow marks text highlighted in that version. "
       r"Text that was moved shows as deleted in its old place and added in its new place. "
       r"Deleted figures are shown small in a red frame and without a number, so the figure numbers are those of the new version. "
       r"New figures have a blue frame. Figure files that were redrawn under the same name show the new drawing in both versions."
       "}}\n\\bigskip\n\n")
# ulem cannot break lines inside nested ulem commands, so \hl{\DIFdel{...}} ran off the page.
# Inside every \hl argument, \DIFdel and \DIFadd become one-level commands that draw the yellow
# highlight and the strike line (or underline) together; plain runs stay \hl.
def match(t, i):
    """index just past the brace group that opens at t[i] == '{'"""
    d = 0
    while True:
        c = t[i]
        if c == '\\':
            i += 2
            continue
        d += c == '{'
        d -= c == '}'
        i += 1
        if d == 0:
            return i
tok = re.compile(r"\\DIF(add|del)\{|\\DIF(add|del)(begin|end)(FL)? ?")
def split_hl(c):
    out, plain, i = [], "", 0
    def flush():
        nonlocal plain
        if plain.strip():
            out.append(r"\hl{" + plain + "}")
        else:
            out.append(plain)
        plain = ""
    while i < len(c):
        m = tok.match(c, i)
        if m and m.group(1):
            flush()
            j = match(c, m.end() - 1)
            out.append(r"\DIF" + m.group(1) + "hl{" + c[m.end():j - 1] + "}")
            i = j
        elif m:
            flush()
            out.append(m.group(0))
            i = m.end()
        elif c[i] == '\\':
            plain += c[i:i + 2]
            i += 2
        else:
            plain += c[i]
            i += 1
    flush()
    return "".join(out)
body0 = s.index(r"\begin{document}")
res, k, nhl = [s[:body0]], body0, 0
while True:
    h = s.find(r"\hl{", k)
    if h < 0:
        res.append(s[k:])
        break
    j = match(s, h + 3)
    res.append(s[k:h])
    res.append(split_hl(s[h + 4:j - 1]))
    nhl += 1
    k = j
s = "".join(res)
print("hl groups rewritten:", nhl)
assert s.count(r"\begin{document}") == 1
s = s.replace(r"\begin{document}", "\\begin{document}\n\n" + box, 1)
open(dst, "w").write(head + s)
EOF
cd "$B"
for i in 1 2 3; do pdflatex -interaction=nonstopmode "$NAME.tex" > "pdflatex_$NAME.$i.log" 2>&1 || true; done
echo "errors: $(grep -c '^!' "$NAME.log" || true)"
grep -E 'Rerun|undefined|multiply' "$NAME.log" || true
pdfinfo "$NAME.pdf" | grep Pages
